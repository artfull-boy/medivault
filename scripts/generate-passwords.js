#!/usr/bin/env node
'use strict';
const crypto = require('crypto');
const fs    = require('fs');
const path  = require('path');

const ROOT = path.resolve(__dirname, '..');

// base64url [A-Za-z0-9_-] — safe in SQL single-quoted strings and env files
function pwd(len = 32) {
  return crypto.randomBytes(Math.ceil(len * 0.75)).toString('base64url').slice(0, len);
}

const gen = {
  POSTGRES_PASSWORD: pwd(40),  // postgres superuser
  PGADMIN_PASSWORD:  pwd(32),
  MEDIVAULT_ENC_KEY: pwd(48),  // column-level encryption key
  PW_DR_HOUSE:       pwd(32),
  PW_DR_WILSON:      pwd(32),
  PW_NURSE_JOY:      pwd(32),
  PW_RECEP_PAM:      pwd(32),
  PW_PAT_ALICE:      pwd(32),
  PW_PAT_BOB:        pwd(32),
  PW_SVC_BILLING:    pwd(32),
  PW_AUD_SMITH:      pwd(32),
  PW_ADM_ROOT:       pwd(32),
};

// --- .env: replace every generated key in .env.example ---
const template = fs.readFileSync(path.join(ROOT, '.env.example'), 'utf8');
const env = Object.entries(gen).reduce(
  (out, [key, val]) => out.replace(new RegExp(`^${key}=.*`, 'm'), `${key}=${val}`),
  template
);
fs.writeFileSync(path.join(ROOT, '.env'), env);
console.log('+ .env written            — set TRUSTED_IP inside, never commit');

// --- config/set-passwords.sql: ALTER USER for password rotation without rebuild ---
const configDir = path.join(ROOT, 'config');
fs.mkdirSync(configDir, { recursive: true });

const userMap = [
  ['dr_house',    gen.PW_DR_HOUSE],
  ['dr_wilson',   gen.PW_DR_WILSON],
  ['nurse_joy',   gen.PW_NURSE_JOY],
  ['recep_pam',   gen.PW_RECEP_PAM],
  ['pat_alice',   gen.PW_PAT_ALICE],
  ['pat_bob',     gen.PW_PAT_BOB],
  ['svc_billing', gen.PW_SVC_BILLING],
  ['aud_smith',   gen.PW_AUD_SMITH],
  ['adm_root',    gen.PW_ADM_ROOT],
];

const sql = [
  '-- Generated by scripts/generate-passwords.js — do not commit',
  '-- Use to rotate passwords without rebuilding the container:',
  '--   docker exec -i medivault_postgres psql -U postgres medivault < config/set-passwords.sql',
  '',
  ...userMap.map(([u, p]) => `ALTER USER ${u} WITH PASSWORD '${p}';`),
  '',
].join('\n');

fs.writeFileSync(path.join(configDir, 'set-passwords.sql'), sql);
console.log('+ config/set-passwords.sql — password rotation script, never commit');

// --- Print summary ---
console.log('\n--- Generated passwords ---');
const labels = {
  POSTGRES_PASSWORD: 'postgres (superuser)',
  PGADMIN_PASSWORD:  'pgadmin UI',
  MEDIVAULT_ENC_KEY: 'encryption key',
  ...Object.fromEntries(userMap.map(([u, p]) => [u, p])),
};
// rebuild with friendly labels
const display = [
  ['postgres (superuser)', gen.POSTGRES_PASSWORD],
  ['pgadmin UI',           gen.PGADMIN_PASSWORD],
  ['encryption key',       gen.MEDIVAULT_ENC_KEY],
  ...userMap,
];
const pad = Math.max(...display.map(([k]) => k.length));
display.forEach(([k, v]) => console.log(`  ${k.padEnd(pad)}  ${v}`));

console.log('\nNext steps:');
console.log('  1. Edit .env — verify TRUSTED_IP=<your-ip>');
console.log('  2. bash scripts/setup.sh');
console.log('  3. docker-compose up -d');
